import React, { useState } from 'react';
import { Coins, MessageSquare, Moon, Printer, X } from 'lucide-react';

interface EndOfDayModalProps {
  onClose: () => void;
  cashSalesPKR: number;
  creditSalesPKR: number;
  totalSalesPKR: number;
  expensesPKR: number;
  purchasesPKR: number;
  grossProfitPKR: number | null;
  netCashInHandPKR: number;
}

export const EndOfDayModal: React.FC<EndOfDayModalProps> = ({
  onClose,
  cashSalesPKR,
  creditSalesPKR,
  totalSalesPKR,
  expensesPKR,
  purchasesPKR,
  grossProfitPKR,
  netCashInHandPKR,
}) => {
  const [countedCashInput, setCountedCashInput] = useState('');
  const countedCashPKR = countedCashInput === '' ? null : Number(countedCashInput);
  const cashDifferencePKR =
    countedCashPKR === null || !Number.isFinite(countedCashPKR)
      ? null
      : countedCashPKR - netCashInHandPKR;
  const dateStr = new Date().toLocaleDateString('en-PK', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const handleShareWhatsApp = () => {
    const text = encodeURIComponent(
      `*End of Day Summary - ${dateStr}*\n\n` +
      `*SALES:*\n• Cash Sales: Rs. ${cashSalesPKR}\n• Credit: Rs. ${creditSalesPKR}\n• Total Sales: Rs. ${totalSalesPKR}\n\n` +
      `*OUTFLOWS:*\n• Expenses: Rs. ${expensesPKR}\n• Purchases: Rs. ${purchasesPKR}\n\n` +
      `*Gross Profit:* ${grossProfitPKR === null ? 'Unavailable' : `Rs. ${grossProfitPKR}`}\n` +
      `*Net Cash in Hand:* Rs. ${netCashInHandPKR}\n\n` +
      `_Generated by the pharmacy management system_`
    );
    window.open(`https://wa.me/?text=${text}`, '_blank');
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/60 backdrop-blur-xs flex items-center justify-center p-4">
      <div className="visual-modal-panel bg-surface rounded-card max-w-sm w-full p-5 shadow-xl border border-border space-y-4">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-border pb-3">
          <div>
            <h3 className="text-base font-black text-text flex items-center gap-2">
              <Moon className="w-4 h-4 text-primary" /> End of Day Summary
            </h3>
            <p className="text-xs text-muted mt-0.5">{dateStr}</p>
          </div>
          <button
            onClick={onClose}
            className="p-1 text-muted hover:text-text rounded-control hover:bg-surface-2"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Breakdown */}
        <div className="space-y-3 text-xs">
          {/* Sales */}
          <div>
            <span className="text-[10px] font-bold text-muted uppercase tracking-wider block mb-1">
              SALES
            </span>
            <div className="space-y-1.5 bg-surface-2 p-2.5 rounded-control border border-border">
              <div className="flex justify-between">
                <span className="text-muted">Cash Sales</span>
                <span className="font-mono font-bold text-text">Rs. {cashSalesPKR}</span>
              </div>
              <div className="flex justify-between">
                <span className="text-muted">Credit</span>
                <span className="font-mono font-bold text-text">Rs. {creditSalesPKR}</span>
              </div>
              <div className="flex justify-between">
                <span className="text-muted">Returns</span>
                <span className="font-mono font-bold text-muted">Unavailable</span>
              </div>
              <div className="flex justify-between border-t border-border pt-1 font-bold">
                <span className="text-text">Total Sales</span>
                <span className="font-mono text-text">Rs. {totalSalesPKR}</span>
              </div>
            </div>
          </div>

          {/* Outflows */}
          <div>
            <span className="text-[10px] font-bold text-muted uppercase tracking-wider block mb-1">
              OUTFLOWS
            </span>
            <div className="space-y-1.5 bg-surface-2 p-2.5 rounded-control border border-border">
              <div className="flex justify-between">
                <span className="text-muted">Expenses</span>
                <span className="font-mono text-danger font-bold">Rs. {expensesPKR}</span>
              </div>
              <div className="flex justify-between">
                <span className="text-muted">Cash Purchases</span>
                <span className="font-mono text-danger font-bold">Rs. {purchasesPKR}</span>
              </div>
            </div>
          </div>

          {/* Profit */}
          <div className="flex justify-between py-1 px-2 text-xs font-bold text-text bg-primary/10 rounded-control border border-primary/20">
            <span>Gross Profit</span>
            <span className="font-mono">{grossProfitPKR === null ? 'Unavailable' : `Rs. ${grossProfitPKR}`}</span>
          </div>

          {/* Net Cash in Hand */}
          <div className="p-3 bg-primary/10 rounded-control border border-primary/30 flex items-center justify-between text-text">
            <span className="font-bold flex items-center gap-1.5">
              <Coins className="w-4 h-4 text-primary" /> Net Cash in Hand
            </span>
            <span className="text-xl font-black font-mono text-primary">
              Rs. {netCashInHandPKR}
            </span>
          </div>
          <div className="space-y-2 rounded-control border border-border bg-surface p-3">
            <label htmlFor="counted-cash" className="block font-bold text-text">
              Counted cash (Rs)
            </label>
            <input
              id="counted-cash"
              type="number"
              min="0"
              step="1"
              value={countedCashInput}
              onChange={(event) => setCountedCashInput(event.target.value)}
              className="w-full rounded-control border border-border px-3 py-2 text-text focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent"
              placeholder="Enter counted cash"
            />
            <div className="flex justify-between text-xs">
              <span className="text-muted">Difference</span>
              <strong className={cashDifferencePKR !== null && cashDifferencePKR < 0 ? 'text-danger' : 'text-primary'}>
                {cashDifferencePKR === null
                  ? 'Enter counted cash'
                  : `Rs ${cashDifferencePKR.toLocaleString('en-PK')}`}
              </strong>
            </div>
          </div>
        </div>

        {/* Actions */}
        <div className="flex items-center gap-2 pt-2 border-t border-border">
          <button
            onClick={() => window.print()}
            className="flex-1 py-2 text-xs font-bold text-text border border-border hover:bg-surface-2 rounded-control flex items-center justify-center gap-1.5 transition"
          >
            <Printer className="w-3.5 h-3.5" /> Print
          </button>
          <button
            onClick={handleShareWhatsApp}
            className="flex-1 py-2 text-xs font-bold text-white bg-primary hover:opacity-90 rounded-control flex items-center justify-center gap-1.5 shadow-xs transition"
          >
            <MessageSquare className="w-3.5 h-3.5" /> WhatsApp
          </button>
          <button
            onClick={onClose}
            className="px-3.5 py-2 text-xs font-semibold text-muted hover:bg-surface-2 rounded-control transition"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
